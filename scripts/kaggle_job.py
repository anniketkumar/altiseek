"""kaggle-job: run AltiSeek stages on a Kaggle kernel and fetch the results (D20).

The kernel clones this repository at a commit that must already be pushed, installs it (only the
packages Kaggle lacks get installed, D13), and rebuilds the M1 tables: prepare-data, fit-camera
and make-splits, all deterministic. It checks that the split ID matches this checkout's, then
runs each ``--run`` command in order. Bulky intermediates live under ``/tmp``. ``/kaggle/working``
(checkpoints, metrics, metadata) is kept by Kaggle and downloaded to ``data/kaggle/<slug>/``.

    MSYS_NO_PATHCONV=1 uv run python scripts/kaggle_job.py --slug altiseek-detector --gpu \
        --run "scripts/make_views.py views_dir=/tmp/views" \
        --run "scripts/train_detector.py views_dir=/tmp/views out_dir=/kaggle/working/detector"

From Git Bash, ``MSYS_NO_PATHCONV=1`` stops ``/tmp/...`` arguments being rewritten into Windows
paths. ``--source <slug>`` attaches a previous kernel's output under ``/kaggle/input/<slug>/``
(e.g. to resume training from its last checkpoint).
"""

import argparse
import json
import re
import subprocess
import sys
import tempfile
import time
from collections.abc import Sequence
from pathlib import Path

REPO_URL = "https://github.com/anniketkumar/altiseek.git"
USER = "aniketkumarpradhan"

RUNNER = '''"""Generated by scripts/kaggle_job.py: AltiSeek stages at commit {commit}."""
import json
import shlex
import shutil
import subprocess
import sys

COMMIT = {commit!r}
SPLIT_ID = {split_id!r}
RUNS = {runs!r}
REPO = "/tmp/altiseek"


def sh(command, cwd=REPO):
    print("+", command, flush=True)
    subprocess.run(shlex.split(command), check=True, cwd=cwd)


sh("git clone --quiet {repo_url} " + REPO, cwd="/tmp")
sh("git checkout --quiet " + COMMIT)
sh(sys.executable + " -m pip install --quiet --no-input -e .")
sh(sys.executable + " -m pip list --format=freeze")
for stage in ("prepare_data", "fit_camera", "make_splits"):
    sh(sys.executable + " scripts/" + stage + ".py")
with open(REPO + "/data/processed/make_splits.meta.json") as fh:
    found = json.load(fh)["split_id"]
assert found == SPLIT_ID, f"split_id {{found}} != expected {{SPLIT_ID}}"
shutil.copytree(REPO + "/data/processed", "/kaggle/working/m1", dirs_exist_ok=True,
                ignore=shutil.ignore_patterns("image_scan", "*.csv"))
for run in RUNS:
    sh(sys.executable + " " + run)
print("all stages finished", flush=True)
'''


def git(*args: str) -> str:
    return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout.strip()


def kaggle(*args: str) -> str:
    result = subprocess.run(["kaggle", *args], capture_output=True, text=True, check=False)
    if result.returncode != 0:
        sys.exit(f"kaggle {' '.join(args)} failed:\n{result.stdout}\n{result.stderr}")
    return result.stdout.strip()


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Run AltiSeek stages on Kaggle.")
    parser.add_argument("--slug", required=True, help="kernel name, e.g. altiseek-detector")
    parser.add_argument("--run", action="append", required=True, help="script path and arguments")
    parser.add_argument("--commit", default=None, help="pushed commit (default: HEAD)")
    parser.add_argument("--gpu", action="store_true", help="2x T4 (accelerator NvidiaTeslaT4)")
    parser.add_argument("--source", action="append", default=[], help="attach a kernel's output")
    parser.add_argument("--timeout-s", type=int, default=None, help="kernel run-time limit")
    parser.add_argument("--wait", action="store_true", help="poll until done, then download")
    args = parser.parse_args(argv)

    for run in args.run:
        # Git Bash rewrites /tmp/... arguments into Windows paths; the kernel runs on Linux.
        if re.search(r"(^|[\s=])[A-Za-z]:[/\\]", run):
            sys.exit(f"Windows path in --run {run!r}: from Git Bash, set MSYS_NO_PATHCONV=1")
    commit = args.commit or git("rev-parse", "HEAD")
    if git("branch", "-r", "--contains", commit) == "":
        sys.exit(f"commit {commit} is not on the remote; push it first")
    meta = json.loads(Path("data/processed/make_splits.meta.json").read_text(encoding="utf-8"))
    runner = RUNNER.format(
        commit=commit, split_id=meta["split_id"], runs=list(args.run), repo_url=REPO_URL
    )
    metadata = {
        "id": f"{USER}/{args.slug}",
        "title": args.slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true" if args.gpu else "false",
        "enable_tpu": "false",
        "enable_internet": "true",
        "machine_shape": "",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [f"{USER}/{s}" for s in args.source],
        "model_sources": [],
    }
    with tempfile.TemporaryDirectory() as tmp:
        Path(tmp, "run.py").write_text(runner, encoding="utf-8")
        Path(tmp, "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), "utf-8")
        push = ["kernels", "push", "-p", tmp]
        if args.gpu:
            push += ["--accelerator", "NvidiaTeslaT4"]
        if args.timeout_s:
            push += ["-t", str(args.timeout_s)]
        print(kaggle(*push))
    print(f"commit {commit}: https://www.kaggle.com/code/{USER}/{args.slug}")
    if not args.wait:
        return
    while True:
        status = kaggle("kernels", "status", f"{USER}/{args.slug}")
        if any(s in status for s in ("COMPLETE", "ERROR", "CANCEL")):
            break
        time.sleep(60)
    print(status)
    out = Path("data/kaggle") / args.slug
    out.mkdir(parents=True, exist_ok=True)
    print(kaggle("kernels", "output", f"{USER}/{args.slug}", "-p", str(out)))
    if "COMPLETE" not in status:
        sys.exit(f"kernel finished with {status}")


if __name__ == "__main__":
    main()
